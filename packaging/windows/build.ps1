<#
.SYNOPSIS
  Builds the Windows release of thermo-desktop: a statically linked
  executable, a portable ZIP and an Inno Setup installer.

.DESCRIPTION
  Run from any directory on Windows with the pinned Rust toolchain and
  Inno Setup 6 (ISCC.exe on PATH or in its default folder). Outputs go to
  target\windows-package by default:
    PropertyEstimationFlowsheet-<version>-x64-portable.zip
    PropertyEstimationFlowsheet-<version>-x64-setup.exe
  and the staged files in target\windows-package\stage.

  The C runtime is linked statically (+crt-static), so no Visual C++
  redistributable is needed. -SkipInstaller builds only the ZIP.
#>
param(
    [string]$Version = "0.0.0",
    [string]$OutDir = "",
    [switch]$SkipInstaller
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
if (-not $OutDir) { $OutDir = Join-Path $root 'target\windows-package' }
$target = 'x86_64-pc-windows-msvc'

Push-Location $root
try {
    # An explicit --target keeps RUSTFLAGS away from build scripts and
    # proc-macros, which must not be linked with a static C runtime.
    # The caller's RUSTFLAGS is restored even when the build fails, so later
    # cargo commands in the same session do not inherit +crt-static.
    $previousRustFlags = $env:RUSTFLAGS
    try {
        $env:RUSTFLAGS = '-C target-feature=+crt-static'
        cargo build --profile dist --target $target -p thermo-desktop --locked
        if ($LASTEXITCODE -ne 0) { throw "cargo build failed ($LASTEXITCODE)" }
    }
    finally {
        if ($null -eq $previousRustFlags) { Remove-Item Env:RUSTFLAGS -ErrorAction SilentlyContinue }
        else { $env:RUSTFLAGS = $previousRustFlags }
    }

    $exe = Join-Path $root "target\$target\dist\thermo-desktop.exe"
    $stage = Join-Path $OutDir 'stage'
    if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
    $notices = Join-Path $stage 'notices'
    New-Item -ItemType Directory -Force $notices | Out-Null

    Copy-Item $exe $stage
    Copy-Item (Join-Path $PSScriptRoot 'README.txt') $stage
    Copy-Item (Join-Path $PSScriptRoot 'NOTICE.txt') $notices
    foreach ($f in 'CoolProp-LICENSE.txt', 'Cantera-License.txt', 'thermo-LICENSE.txt') {
        Copy-Item (Join-Path $root "data\source-extracts\$f") $notices
    }

    # Crates compiled into the executable (normal dependencies only).
    $meta = cargo metadata --format-version 1 --locked --filter-platform $target | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed" }
    $byId = @{}
    foreach ($p in $meta.packages) { $byId[$p.id] = $p }
    $nodes = @{}
    foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
    $start = ($meta.packages | Where-Object { $_.name -eq 'thermo-desktop' }).id
    $seen = @{}
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue($start)
    while ($queue.Count -gt 0) {
        $id = $queue.Dequeue()
        if ($seen.ContainsKey($id)) { continue }
        $seen[$id] = $true
        foreach ($d in $nodes[$id].deps) {
            $normal = $d.dep_kinds | Where-Object { $null -eq $_.kind }
            if ($normal) { $queue.Enqueue($d.pkg) }
        }
    }
    $lines = @(
        'Rust crates compiled into thermo-desktop.exe (generated by build.ps1 from Cargo.lock).',
        'Name Version | License | Repository',
        ''
    )
    $lines += $seen.Keys | ForEach-Object { $byId[$_] } | Sort-Object name, version | ForEach-Object {
        "$($_.name) $($_.version) | $($_.license) | $($_.repository)"
    }
    Set-Content -Encoding utf8 -Path (Join-Path $notices 'THIRD-PARTY-CRATES.txt') -Value $lines

    $base = "PropertyEstimationFlowsheet-$Version-x64"
    $zip = Join-Path $OutDir "$base-portable.zip"
    if (Test-Path $zip) { Remove-Item $zip }
    Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zip

    if (-not $SkipInstaller) {
        $iscc = (Get-Command ISCC.exe -ErrorAction SilentlyContinue).Source
        if (-not $iscc) { $iscc = Join-Path ${env:ProgramFiles(x86)} 'Inno Setup 6\ISCC.exe' }
        if (-not (Test-Path $iscc)) { throw "Inno Setup 6 (ISCC.exe) not found" }
        & $iscc /Q "/DAppVersion=$Version" "/DStageDir=$stage" "/DOutputDir=$OutDir" (Join-Path $PSScriptRoot 'thermo-desktop.iss')
        if ($LASTEXITCODE -ne 0) { throw "ISCC failed ($LASTEXITCODE)" }
    }

    Get-ChildItem $OutDir -File | ForEach-Object {
        '{0,-60} {1,10:N0} bytes' -f $_.Name, $_.Length
    }
    '{0,-60} {1,10:N0} bytes' -f 'stage\thermo-desktop.exe', (Get-Item (Join-Path $stage 'thermo-desktop.exe')).Length
}
finally {
    Pop-Location
}
